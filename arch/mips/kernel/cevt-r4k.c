/*
 * MIPS R4K CP0 Count/Compare Timer Interrupt Handler
 *
 * Hardware flow:
 *
 *   CP0_COUNT
 *        |
 *        | COUNT >= CP0_COMPARE
 *        |
 *        v
 *   Timer Interrupt (IP7)
 *        |
 *        v
 *   c0_compare_interrupt()
 *        |
 *        v
 *   clock_event_device->event_handler()
 *        |
 *        v
 *   tick_handle_periodic()
 *        |
 *        v
 *   scheduler_tick()
 *        |
 *        v
 *   CFS / PELT update
 *
 * For EcoNet EN7561DU:
 *
 *   MIPS32 1004Kc CPS
 *
 *   Core
 *    |
 *    +-- VPE0 -> Linux CPU0
 *    |
 *    +-- VPE1 -> Linux CPU1
 *
 * Each VPE has its own CP0_COUNT/COMPARE timer.
 */


 irqreturn_t c0_compare_interrupt(int irq, void *dev_id)
 {
	 /*
	  * MIPS architecture revision.
	  *
	  * MIPS32 Release 2 introduced additional interrupt status
	  * information, including performance counter pending bit.
	  *
	  * Older MIPS (R1):
	  *   Timer interrupt and performance counter interrupt
	  *   may share the same interrupt line.
	  */
	 const int r2 = cpu_has_mips_r2;
 
 
	 /*
	  * Linux generic clock event abstraction.
	  *
	  * This object represents the MIPS CP0 Count/Compare timer
	  * as a clock_event_device.
	  *
	  * Later this will call:
	  *
	  *     cd->event_handler(cd)
	  *
	  * which eventually reaches:
	  *
	  *     tick_handle_periodic()
	  *          |
	  *          +--> scheduler_tick()
	  *
	  */
	 struct clock_event_device *cd;
 
 
	 /*
	  * CP0 Count/Compare timer is per CPU.
	  *
	  * For MIPS1004K CPS:
	  *
	  *     VPE0 -> Linux CPU0
	  *     VPE1 -> Linux CPU1
	  *
	  * Each CPU has its own:
	  *
	  *     CP0_COUNT
	  *     CP0_COMPARE
	  *
	  */
	 int cpu = smp_processor_id();
 
 
 
	 /*
	  * ---------------------------------------------------------
	  * Handle Performance Counter Interrupt
	  * ---------------------------------------------------------
	  *
	  * Before MIPS32 Release 2:
	  *
	  * There was no hardware bit indicating whether
	  * Performance Counter interrupt was pending.
	  *
	  * Therefore when an interrupt arrives, Linux has to
	  * try the performance counter handler first.
	  *
	  * If performance counter interrupt was the real source:
	  *
	  *     handle_perf_irq()
	  *
	  * returns true and we finish here.
	  *
	  */
	 if (handle_perf_irq(r2))
		 goto out;
 
 
 
	 /*
	  * ---------------------------------------------------------
	  * Confirm this is really a Timer Interrupt
	  * ---------------------------------------------------------
	  *
	  * MIPS R2 provides Cause register information:
	  *
	  * CP0_CAUSE bit 30:
	  *
	  *     Performance Counter Interrupt Pending
	  *
	  *
	  * For R1:
	  *
	  *     !r2 == true
	  *
	  * because we cannot distinguish it.
	  *
	  *
	  * For R2:
	  *
	  *     read_c0_cause() & (1 << 30)
	  *
	  * confirms the interrupt source.
	  *
	  *
	  * Timer interrupt itself is:
	  *
	  *     CP0 Cause.IP7
	  *
	  * generated by:
	  *
	  *     CP0_COUNT >= CP0_COMPARE
	  *
	  */
	 if (!r2 || (read_c0_cause() & (1 << 30))) {
 
 
		 /*
		  * -----------------------------------------------------
		  * Clear Count/Compare Interrupt
		  * -----------------------------------------------------
		  *
		  * MIPS Timer interrupt condition:
		  *
		  *     COUNT >= COMPARE
		  *
		  *
		  * Example:
		  *
		  *     COUNT    = 100000
		  *     COMPARE  = 100000
		  *
		  * Timer IRQ becomes pending:
		  *
		  *     Cause.IP7 = 1
		  *
		  *
		  * If COMPARE is not acknowledged,
		  * the condition remains true and the CPU may
		  * repeatedly enter the interrupt handler.
		  *
		  *
		  * Writing COMPARE back acknowledges the timer event.
		  *
		  */
		 write_c0_compare(read_c0_compare());
 
 
 
		 /*
		  * Get this CPU's clock event device.
		  *
		  * Defined as:
		  *
		  * DEFINE_PER_CPU(
		  *      struct clock_event_device,
		  *      mips_clockevent_device);
		  *
		  *
		  * Example:
		  *
		  * CPU0:
		  *      mips_clockevent_device[0]
		  *
		  * CPU1:
		  *      mips_clockevent_device[1]
		  *
		  */
		 cd = &per_cpu(mips_clockevent_device, cpu);
 
 
 
		 /*
		  * Enter Linux clock event framework.
		  *
		  * Normally this eventually calls:
		  *
		  *     tick_handle_periodic()
		  *
		  * Then:
		  *
		  *     update_process_times()
		  *
		  * Then:
		  *
		  *     scheduler_tick()
		  *
		  * Finally:
		  *
		  *     task_tick_fair()
		  *
		  *     update_load_avg()
		  *
		  *     PELT update
		  *
		  */
		 cd->event_handler(cd);
	 }
 
 
 out:
 
	 /*
	  * Tell Linux IRQ subsystem:
	  *
	  * This interrupt has been handled.
	  *
	  */
	 return IRQ_HANDLED;
 }

struct irqaction c0_compare_irqaction = {
	.handler = c0_compare_interrupt,
	.flags = IRQF_PERCPU | IRQF_TIMER,
	.name = "timer",
};


